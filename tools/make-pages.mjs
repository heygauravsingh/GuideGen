#!/usr/bin/env node
// Writes web/solutions/* and web/compare/* from tools/pages.data.mjs.
//
//   node tools/make-pages.mjs           write the pages
//   node tools/make-pages.mjs --check   fail if any page is stale
//
// ## Why these are generated rather than hand-written
//
// There are fourteen of them and they share a head, a house bar, a header, a footer
// and a call to action. Hand-written, they drift: one page keeps an old nav link,
// another misses a meta tag, and the one nobody re-reads still says `.webm`. The
// content lives in `pages.data.mjs` so the writing can be edited without touching a
// template, and `--check` — wired into the same command as the icon and web-asset
// checks — fails the build if a page on disk no longer matches the data.
//
// The shell is copied from the hand-written pages rather than shared at runtime,
// because this is a static site with no build step for the reader: every page has to
// stand alone as a file Vercel can serve.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { SOLUTIONS, COMPARISONS } from "./pages.data.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const WEB = path.join(ROOT, "web");
const SITE = "https://guidegen.backpocket.website";
const STORE = "https://chromewebstore.google.com/detail/dijeonandicniffeffbcolhfldommhnp";

const esc = (s) =>
  String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/* Strips the markup we allow inside body copy, so a meta description is never a tag
   soup. The data deliberately carries a little <b> and <code>; a description must not. */
const plain = (s) => String(s).replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();

