// ---------------------------------------------------------------- write / check

const files = [
  ["solutions/index.html", solutionsIndex()],
  ["compare/index.html", compareIndex()],
  ...SOLUTIONS.map((s) => [`solutions/${s.slug}.html`, solutionPage(s)]),
  ...COMPARISONS.map((c) => [`compare/${c.slug}.html`, comparePage(c)]),
];

const check = process.argv.includes("--check");
let stale = 0;

for (const [rel, html] of files) {
  const dest = path.join(WEB, rel);
  const cur = fs.existsSync(dest) ? fs.readFileSync(dest, "utf8") : null;
  if (cur === html) continue;
  if (check) {
    console.log(`stale: web/${rel}`);
    stale++;
  } else {
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, html);
  }
}

if (check) {
  if (stale) {
    console.log(`\n${stale} page(s) out of date. Run: node tools/make-pages.mjs`);
    process.exit(1);
  }
  console.log(`solutions and comparison pages match tools/pages.data.mjs (${files.length} files)`);
} else {
  console.log(`wrote ${files.length} pages into web/solutions and web/compare`);
}
