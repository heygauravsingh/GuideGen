#!/usr/bin/env node
// Rebuilds the FAQPage structured data on web/index.html from the FAQ that is actually on it.
//
//   node tools/make-faq-schema.mjs           write the block
//   node tools/make-faq-schema.mjs --check   fail if it has drifted from the page
//
// ## Why this is generated and not written by hand
//
// Structured data has one hard rule: it must match what the reader sees. A hand-written
// FAQ block is correct on the day it is written and wrong the first time somebody edits
// an answer — and wrong structured data is worse than none, because it describes a page
// that does not exist. There are 21 questions here. Nobody is going to keep two copies
// of 21 answers in step by hand.
//
// So the page is the source of truth: this reads the `<details>` blocks out of the FAQ
// section and rebuilds the JSON from them. `--check` is in the same gate as the other
// generators, so editing an answer and forgetting to re-run this fails the build.
//
// ## What it is actually worth
//
// Google restricted FAQ *rich results* to authoritative government and health sites, so
// this will not put dropdowns under the listing. It is still worth having: it tells a
// crawler which text on the page is a question and which is its answer, which is how the
// page gets understood as answering "is GuideGen free" rather than as a wall of prose.
// Do not add it expecting stars in the results.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PAGE = path.join(ROOT, "web", "index.html");
const OPEN = "<!-- FAQ-SCHEMA-BEGIN — generated by tools/make-faq-schema.mjs. Do not edit by hand. -->";
const CLOSE = "<!-- FAQ-SCHEMA-END -->";

/* Tags out, entities back to characters, whitespace collapsed. The answers carry <b>,
   <em>, <code> and links; structured data wants the sentence a person reads, not the
   markup around it. */
function plain(html) {
  return html
    .replace(/<[^>]+>/g, "")
    .replace(/&mdash;/g, "—").replace(/&ndash;/g, "–")
    .replace(/&ldquo;/g, "“").replace(/&rdquo;/g, "”")
    .replace(/&rsquo;/g, "’").replace(/&lsquo;/g, "‘")
    .replace(/&hellip;/g, "…").replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"').replace(/&#39;/g, "'")
    .replace(/\s+/g, " ")
    .trim();
}

const src = fs.readFileSync(PAGE, "utf8");

const secStart = src.indexOf('<section id="faq">');
if (secStart === -1) {
  console.log("FAIL  no #faq section on web/index.html");
  process.exit(1);
}
const section = src.slice(secStart, src.indexOf("</section>", secStart));

const pairs = [...section.matchAll(/<summary>([\s\S]*?)<\/summary>\s*<p>([\s\S]*?)<\/p>/g)]
  .map((m) => ({ q: plain(m[1]), a: plain(m[2]) }))
  .filter((p) => p.q && p.a);

if (!pairs.length) {
  console.log("FAIL  the #faq section has no question/answer pairs");
  process.exit(1);
}

const json = {
  "@context": "https://schema.org",
  "@type": "FAQPage",
  mainEntity: pairs.map((p) => ({
    "@type": "Question",
    name: p.q,
    acceptedAnswer: { "@type": "Answer", text: p.a },
  })),
};

const block =
  OPEN +
  '\n<script type="application/ld+json">\n' +
  JSON.stringify(json, null, 2) +
  "\n</script>\n" +
  CLOSE;

const has = src.includes(OPEN);
const next = has
  ? src.slice(0, src.indexOf(OPEN)) + block + src.slice(src.indexOf(CLOSE) + CLOSE.length)
  : src.replace("</head>", block + "\n</head>");

if (process.argv.includes("--check")) {
  if (next !== src) {
    console.log("stale: web/index.html FAQ schema no longer matches the FAQ on the page");
    console.log("       run: node tools/make-faq-schema.mjs");
    process.exit(1);
  }
  console.log(`FAQ schema matches the page (${pairs.length} questions)`);
} else {
  fs.writeFileSync(PAGE, next);
  console.log(`wrote FAQPage schema with ${pairs.length} questions`);
}
